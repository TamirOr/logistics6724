-- The measures the battalion already counts these items in, offered in the
-- add row's dropdown from the first request.
insert into item_measures (item_id, name)
select i.id, m.measure
from items i
join units u on u.id = i.supplier_id and u.kind = 'supplier'
join (values
  ('אפסנאות', 'שמרים יבשים', 'קופסה'),
  ('אפסנאות', 'קוסקוס', 'שקית'),
  ('אפסנאות', 'כוסות חמות', 'קרטון'),
  ('אפסנאות', 'נייר כסף', 'גליל'),
  ('אפסנאות', 'מגבוני שדה', 'דלי')
) as m (supplier, item, measure) on m.supplier = u.name and m.item = i.name
on conflict do nothing;
